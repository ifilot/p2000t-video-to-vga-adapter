    ; fills the count and checksum after assembly.
    db 0x5e, 0x00, 0x00, 0x00, 0x00
    db "SAA5050TEST"

    jp start

start:
    ; Initialize both 40-column pages so no stale video RAM remains.
    ld a,' '
    ld hl,0x5000
    ld (hl),a
    ld de,0x5001
    ld bc,0x07ff
    ldir

    ; Copy one 40-byte source row, then skip the alternate-page half-row.
    ld hl,screen_data
    ld de,0x5000
    ld a,24

copy_row:
    ex af,af'
    ld bc,40
    ldir
    ex de,hl
    ld bc,40
    add hl,bc
    ex de,hl
    ex af,af'
    dec a
    jr nz,copy_row

idle:
    halt
    jr idle

