/** Return one row from the shared five-by-seven firmware font. */
static inline uint8_t p2000t_no_signal_glyph_row(char character,
                                                  unsigned row) {
    if (row >= NO_SIGNAL_GLYPH_HEIGHT) {
        return 0u;
    }
    if (character >= 'A' && character <= 'Z') {
        return p2000t_no_signal_font[(unsigned)(character - 'A')][row];
    }
    if (character >= '0' && character <= '9') {
        return p2000t_no_signal_font[26u + (unsigned)(character - '0')][row];
    }
    return character == '.' && row == 6u ? 0x04u : 0x00u;
}

