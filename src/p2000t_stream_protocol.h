#ifndef P2000T_STREAM_PROTOCOL_H
#define P2000T_STREAM_PROTOCOL_H

/**
 * @file p2000t_stream_protocol.h
 * @brief Binary USB framebuffer protocol shared by firmware and viewer.
 */

enum {
    P2000T_STREAM_PROTOCOL_VERSION = 3,
    P2000T_STREAM_HEADER_SIZE = 64,
    P2000T_STREAM_WIDTH = 480,
    P2000T_STREAM_HEIGHT = 240,
    P2000T_STREAM_PLANE_STRIDE = P2000T_STREAM_WIDTH / 8,
    P2000T_STREAM_PLANE_SIZE =
        P2000T_STREAM_PLANE_STRIDE * P2000T_STREAM_HEIGHT,
    P2000T_STREAM_PAYLOAD_SIZE = 3 * P2000T_STREAM_PLANE_SIZE,

    P2000T_STREAM_ENCODING_RAW = 1,
    P2000T_STREAM_ENCODING_PACKBITS = 2,
    P2000T_STREAM_ENCODING_CONFIGURATION = 3,

    P2000T_STREAM_FLAG_PLANAR_RGB111 = 1u << 0,
    P2000T_STREAM_FLAG_PIXELS_MSB_FIRST = 1u << 1,
    P2000T_STREAM_FLAG_TIMING_DIAGNOSTICS = 1u << 2,
    P2000T_STREAM_FLAG_SIGNAL_PRESENT = 1u << 3,
    P2000T_STREAM_FLAG_CONFIGURATION_STATE = 1u << 4,
    P2000T_STREAM_FLAG_CAPTURE_DEADLINE_MISS = 1u << 5,

    P2000T_STREAM_ARTWORK_GREEN_PHOSPHOR = 0,
    P2000T_STREAM_ARTWORK_SYNTHWAVE = 1,
    P2000T_STREAM_ARTWORK_AMBER_CIRCUIT = 2,
    P2000T_STREAM_ARTWORK_COUNT = 3,

    /** Byte offset of the selected no-connection artwork in the header. */
    P2000T_STREAM_ARTWORK_OFFSET = 40,
    P2000T_STREAM_RECONSTRUCTION_OFFSET = 41,
    P2000T_STREAM_CAPTURE_ENGINE_OFFSET = 42,
    P2000T_STREAM_SAMPLES_PER_OUTPUT_OFFSET = 43,
    P2000T_STREAM_CORRECTED_SAMPLES_OFFSET = 44,
    P2000T_STREAM_AMBIGUOUS_SAMPLES_OFFSET = 48,
    P2000T_STREAM_RED_CORRECTIONS_OFFSET = 52,
    P2000T_STREAM_GREEN_CORRECTIONS_OFFSET = 56,
    P2000T_STREAM_BLUE_CORRECTIONS_OFFSET = 60,
};

#define P2000T_STREAM_MAGIC "P2TF"

#endif
